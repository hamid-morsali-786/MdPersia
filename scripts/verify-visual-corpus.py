"""Explicitly update or compare reviewed PDF/Word page baselines on Windows.

Requires Pillow, Poppler, Word and the project conversion dependencies.
Never updates baselines implicitly. Run from repository root.
"""
import argparse
import json
import subprocess
import sys
from pathlib import Path
from PIL import Image, ImageChops, ImageStat

CASES = ['math-bilingual', 'export-bilingual', 'lists-bilingual']


def compare(actual, expected, diff_path):
    with Image.open(actual) as a, Image.open(expected) as b:
        a, b = a.convert('RGB'), b.convert('RGB')
        if a.size != b.size:
            raise AssertionError(f'Page size changed: {actual}')
        diff = ImageChops.difference(a, b)
        changed = sum(any(v > 16 for v in pixel) for pixel in diff.getdata()) / (a.width * a.height)
        mean = sum(ImageStat.Stat(diff).mean) / 3
        if changed > .002 or mean > .5:
            diff.save(diff_path)
            raise AssertionError(f'Visual regression {actual}: changed={changed:.4%}, mean={mean:.3f}; {diff_path}')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--update', action='store_true', help='Explicitly replace reviewed baselines')
    parser.add_argument('--output', type=Path, default=Path('output/visual-corpus'))
    parser.add_argument('--baseline', type=Path, default=Path('output/visual-baselines/windows-word16'))
    args = parser.parse_args()
    root = Path.cwd()
    baseline = args.baseline.resolve()
    if not args.update and not (baseline / 'manifest.json').is_file():
        parser.error('Local baseline missing; first run with --update and review the generated images.')
    output = args.output.resolve()
    output.mkdir(parents=True, exist_ok=True)
    if list(output.glob('*.png')):
        raise ValueError('Use a fresh --output directory to exclude stale pages')
    documents = []
    for case in CASES:
        source = (root / f'tests/fixtures/{case}.md').resolve()
        for fmt in ['pdf', 'docx']:
            target = output / f'{case}.{fmt}'
            subprocess.run([sys.executable, '-m', 'fa_md_pdf.cli', str(source), '--format', fmt,
                            '--output', str(target)], check=True)
        documents.append(output / f'{case}.docx')
    # Separate automation instance; never attach to or close the user's Word.
    quoted = ','.join("'" + str(p).replace("'", "''") + "'" for p in documents)
    ps = output / 'render-word.ps1'
    ps.write_text('''$ErrorActionPreference = 'Stop'
$qaWord = New-Object -ComObject Word.Application
$qaWord.Visible = $false
$qaWord.DisplayAlerts = 0
try {
 foreach ($file in @(''' + quoted + ''')) {
  $doc = $qaWord.Documents.Open($file, $false, $true)
  try { $doc.ExportAsFixedFormat($file + '.pdf', 17) } finally { $doc.Close(0) }
 }
} finally { $qaWord.Quit() }
''', encoding='utf-8-sig')
    subprocess.run(['pwsh', '-NoProfile', '-File', str(ps)], check=True)
    for case in CASES:
        for suffix in ['.pdf', '.docx.pdf']:
            subprocess.run(['pdftoppm', '-r', '72', '-png', str(output / (case + suffix)),
                            str(output / (case + suffix))], check=True)
    pages = sorted(output.glob('*.png'))
    # Select only pages generated by this run, rejecting stale pages via counts
    # from Poppler outputs in a fresh --output directory.
    if not pages:
        raise AssertionError('No rendered pages')
    if args.update:
        baseline.mkdir(parents=True, exist_ok=True)
        for page in pages:
            (baseline / page.name).write_bytes(page.read_bytes())
        (baseline / 'manifest.json').write_text(json.dumps([p.name for p in pages], indent=2))
    else:
        expected = json.loads((baseline / 'manifest.json').read_text())
        assert [p.name for p in pages] == expected, 'Page count/names changed'
        for page in pages:
            compare(page, baseline / page.name, output / ('diff-' + page.name))
    print(f'{len(pages)} PDF/Word pages: ' + ('baseline written; review images' if args.update else 'visual comparison passed'))


if __name__ == '__main__':
    main()
